import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('Мой центр: каталог, пользовательские ярлыки, открытие, порядок, перезагрузка и резервная копия', async ({ page, context }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const button = (name: string) => page.getByRole('button', { name, exact: true })
  const panel = page.getByRole('region', { name: 'Мои ярлыки' })
  const dialog = page.getByRole('dialog')
  const rows = () => panel.getByRole('link')
  const open = () => button('Мой центр').click()
  const add = () => panel.getByRole('button', { name: 'Добавить ярлык' }).click()
  const save = async () => {
    await dialog.getByRole('button', { name: 'Сохранить ярлык' }).click()
    await expect(dialog).toHaveCount(0)
  }
  const backupInput = () => page.locator('.app-settings input[type=file]')

  await page.goto('/')
  await expect(button('Предстоящие платежи')).toBeVisible()
  await open()
  await expect(rows()).toHaveCount(0)
  await add()
  await dialog.getByRole('button', { name: 'Telegram', exact: true }).click()
  await expect(dialog.getByLabel('Название')).toHaveValue('Telegram')
  await expect(dialog.getByLabel('HTTPS-ссылка')).toHaveValue('https://t.me/')
  await dialog.getByLabel('HTTPS-ссылка').fill('https://t.me/example')
  await save()
  await expect(rows()).toHaveText(['Telegram'])

  await add()
  await dialog.getByLabel('Название').fill('Личный проект')
  await dialog.getByLabel('HTTPS-ссылка').fill('file:///tmp/test')
  await expect(dialog.getByRole('button', { name: 'Сохранить ярлык' })).toBeDisabled()
  await dialog.getByLabel('HTTPS-ссылка').fill('https://example.org/project')
  await save()
  await button('Управлять ярлыками').click()
  await button('Передвинуть «Личный проект» ближе к началу').click()
  await expect(rows()).toHaveText(['Личный проект', 'Telegram'])
  await button('Изменить ярлык «Telegram»').click()
  await dialog.getByLabel('Название').fill('Рабочий канал')
  await dialog.getByLabel('HTTPS-ссылка').fill('https://t.me/work')
  await save()
  await expect(panel.getByRole('link', { name: 'Рабочий канал' })).toHaveAttribute('href', 'https://t.me/work')

  await context.route('https://example.org/project', route => route.fulfill({ body: 'Открытый проект' }))
  const opened = page.waitForEvent('popup')
  await panel.getByRole('link', { name: 'Личный проект' }).click()
  const external = await opened
  await expect(external).toHaveURL('https://example.org/project')
  await external.close()

  await page.reload()
  await open()
  await expect(rows()).toHaveText(['Личный проект', 'Рабочий канал'])
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await button('Настройки').click()
  await page.getByRole('checkbox', { name: 'Светлая тема' }).check()
  const exported = page.waitForEvent('download')
  await button('Экспорт JSON').click()
  const json = await readFile((await (await exported).path())!, 'utf8')
  expect(JSON.parse(json).shortcuts.map(item => item.title)).toEqual(['Личный проект', 'Рабочий канал'])

  await button('Назад').click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await button('Управлять ярлыками').click()
  await button('Удалить ярлык «Личный проект»').click()
  await button('Подтвердить').click()
  await expect(rows()).toHaveText(['Рабочий канал'])

  await button('Настройки').click()
  await backupInput().setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(json) })
  await expect(dialog).toContainText('ярлыки')
  await button('Подтвердить').click()
  await open()
  await expect(rows()).toHaveText(['Личный проект', 'Рабочий канал'])
})
