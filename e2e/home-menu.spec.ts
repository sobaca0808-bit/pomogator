import { expect, test } from '@playwright/test'

test('компактное меню и действия с разделами на узком телефоне', async ({ browser, baseURL }) => {
  const context = await browser.newContext({ viewport: { width: 320, height: 700 }, isMobile: true, hasTouch: true })
  try {
    const page = await context.newPage()
    const button = (name: string) => page.getByRole('button', { name, exact: true })
    await page.goto(baseURL!)
    const menu = page.locator('.navigation-menu')
    const toggle = menu.locator('summary')
    const sections = page.locator('.overview-places')
    await expect(button('Мой центр')).toBeInViewport()
    await expect(button('Календарь')).toHaveCount(0)
    await toggle.tap()
    await expect(menu.getByRole('button')).toHaveCount(9)
    await expect(menu.getByRole('button', { name: 'Обзор', exact: true })).toHaveAttribute('aria-current', 'page')
    const list = menu.locator('.disclosure-panel')
    expect(await list.evaluate(element => element.scrollWidth)).toBeLessThanOrEqual((await list.boundingBox())!.width)
    await toggle.press('Escape')
    await expect(menu).not.toHaveAttribute('open')
    await expect(toggle).toBeFocused()

    const title = 'Долгосрочные семейные проекты'
    await button('Добавить раздел').tap()
    await page.getByLabel('Название').fill(title)
    await button('Сохранить').tap()
    const card = sections.getByRole('article').filter({ hasText: title })
    await expect(card).toBeVisible()
    const actions = card.locator('summary')
    expect((await actions.boundingBox())!.height).toBeGreaterThanOrEqual(44)
    expect((await card.getByRole('button', { name: new RegExp(title) }).boundingBox())!.height).toBeGreaterThanOrEqual(44)
    await actions.tap()
    await button(`Передвинуть «${title}» выше`).tap()
    await expect(sections.getByRole('article').nth(5)).toContainText(title)

    await actions.tap()
    await button(`Настроить «${title}»`).tap()
    const renamed = title + ' и планы'
    await page.getByLabel('Название').fill(renamed)
    await button('Сохранить').tap()
    const renamedCard = sections.getByRole('article').filter({ hasText: renamed })
    await expect(renamedCard).toBeVisible()
    await renamedCard.getByRole('button', { name: new RegExp(renamed) }).tap()
    await button('Папка').tap()
    await page.getByLabel('Название').fill('Вложенная папка')
    await button('Сохранить').tap()
    await expect(page.getByRole('button', { name: /^Вложенная папка 0 пап/ })).toBeVisible()
    await button('Назад').tap()

    await renamedCard.locator('summary').tap()
    await button(`Удалить «${renamed}»`).tap()
    await expect(page.getByRole('dialog')).toContainText('Вложенных папок: 1')
    await button('Отмена').tap()
    await expect(renamedCard).toBeVisible()
    await renamedCard.locator('summary').tap()
    await button(`Удалить «${renamed}»`).tap()
    await button('Подтвердить').tap()
    await expect(renamedCard).toHaveCount(0)
    await button('Отменить удаление').tap()
    await expect(renamedCard).toContainText('1 пап.')
  } finally { await context.close() }
})
